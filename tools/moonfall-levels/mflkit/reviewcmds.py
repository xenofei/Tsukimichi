# ------------------------------------------------------------------------------------------------------- selftest
def _lv(pegs, bricks=()):
    return {"pegs": [dict(x=x, y=y, r=10, canBeOrange=o) for (x, y, o) in pegs], "bricks": list(bricks)}


def selftest(verbose=True):
    cases = []

    def add(name, good):
        cases.append((name, bool(good)))
    brick = dict(kind="line", x1=300, y1=300, x2=360, y2=300, thickness=20, canBeOrange=False)
    old = _lv([(200, 200, True), (300, 200, False), (400, 200, True), (500, 200, False)], [brick])
    new = _lv([(200, 200, False), (300, 230, False), (400, 200, True), (600, 400, True)], [dict(brick, y1=320, y2=320)])
    d = review.diff_pieces(old, new)
    add("diff: two pieces in place ((400,200), and (200,200) whose candidacy changed)", len(d["same"]) == 2)
    add("diff: the peg that stepped 30 units and the brick that dropped 20 are moved", len(d["moved"]) == 2)
    add("diff: (500,200) went and (600,400) came, 100+ units apart", len(d["added"]) == 1 and len(d["removed"]) == 1)
    add("diff: (200,200) stopped being a candidate", len(d["lost"]) == 1 and len(d["gained"]) == 0)
    d2 = review.diff_pieces(old, old)
    add("diff: a level against itself changes nothing", len(d2["same"]) == 5 and not (d2["moved"] or d2["added"] or d2["removed"]))
    d3 = review.diff_pieces(_lv([]), new)
    add("diff: against an empty level every piece is added", len(d3["added"]) == 5)
    add("code: 3-1 for number 11 of stage 3", review.code_of(3, 11) == "3-1" and review.code_of(3, 15) == "3-5")
    # pictures
    sky = np.full((600, 800, 3), 0.1, np.float32)
    img = reviewimg.diff_image(sky, sky, d, "old", "new", ["pieces 5 -> 5", "x"])
    add("diff image: at most 1568 px wide", img.width <= reviewimg.MAX_W and img.height > 500)
    px = np.asarray(img)
    add("diff image: the added ring is drawn", (np.abs(px.astype(int) - np.array(reviewimg.ADDED)).sum(-1) < 30).any())
    add("diff image: the removed ring is drawn", (np.abs(px.astype(int) - np.array(reviewimg.REMOVED)).sum(-1) < 30).any())
    cap = [("3-1  base-11", reviewimg.FG, True), ("Name", reviewimg.FG, False)]
    sh = reviewimg.sheet_image("t", [{"composite": sky, "caption": cap}] * 7, cols=5)
    add("sheet: seven cells wrap to two rows, 1568 wide", sh.width == reviewimg.MAX_W and sh.height > 500)
    add("sheet: a missing composite does not fail", reviewimg.sheet_image("t", [{"composite": None, "caption": cap}]).width == reviewimg.MAX_W)
    rows = [dict(id="base-11", code="3-1", has_file=True, verdict="PASS", build="fresh", pieces=90, candidates=70, lower_third=0.2,
                 won48=20, ramp=18.5, margin=-0.4, convert="stale", precheck="WARN", changed_since_review=["x/y.py"]),
            dict(id="base-12", code="3-2", has_file=False)]
    t = review.status_text(rows)
    add("status: row text carries build, margin, convert and the changed files", all(s in t for s in ("fresh", "-0.4", "stale", "y.py", "no level file")))
    ok = all(g for _n, g in cases)
    if verbose:
        for n, g in cases:
            print(f"  {'ok ' if g else 'BAD'} review: {n}")
    return ok


if __name__ == "__main__":
    sys.exit(0 if selftest() else 1)
