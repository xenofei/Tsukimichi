"""The review commands of mfl.py: diff, sheet, status and pack (README, "Review tools").

mfl.py registers COMMANDS from here, so the commands live in one module and mfl.py stays a thin dispatcher. None of them
builds a level: they read the committed files, reports and composites (and, for engine renders, the plugin's renderer)."""
import json
import pathlib
import shutil
import sys
import time

import numpy as np

from . import paths, precheck, review, reviewimg, stagecheck

SHEETS = paths.BUILD / "sheets"
DIFFS = paths.BUILD / "diff"
MARK = "<!-- generated by mfl.py pack: delete this line to keep your edits -->"


def _take(args, flag, default=None, has_value=True):
    if flag not in args:
        return default, args
    i = args.index(flag)
    if not has_value:
        return True, args[:i] + args[i + 1:]
    return args[i + 1], args[:i] + args[i + 2:]


# ------------------------------------------------------------------------------------------------------------ diff
def composite_at(src, lid, note):
    """The level's 1x composite at a revision; when that revision has none (a level not built yet then), regenerated from its
    level file and recipe in scratch, and when that cannot be done either, a dark board (the rings still show the pieces)."""
    arr = src.image(f"composites/{lid}.png")
    if arr is not None:
        return arr
    L = precheck.Level(src, lid)
    try:
        import tempfile
        from . import composite, dress as dr, engine, scene
        if not (L.file and L.recipe):
            raise RuntimeError("no level file or recipe at that revision")
        g = scene.graded(L.recipe, 1)
        d1, _ctx = dr.dress(L.recipe, g, L.file, 1)
        tmp = pathlib.Path(tempfile.mkdtemp(prefix="mfl-diff-")) / f"{lid}.json"
        tmp.write_text(json.dumps(L.file), encoding="utf-8")
        cols = engine.colours(tmp, L.number or 1, 1)
        note.append(f"{lid}: composite regenerated from the level file at {src.rev or 'now'}")
        return np.asarray(composite.render(L.file, L.recipe, d1, cols, S=1, stage=L.stage or 1, number=L.number or 1), np.float32)
    except Exception as e:
        note.append(f"{lid}: no composite at {src.rev or 'now'} and none could be regenerated ({type(e).__name__}: {e}); dark board")
        return np.full((600, 800, 3), 0.06, np.float32)


def diff_level(lid, rev, out=None):
    """Write the diff PNG; returns (path, summary lines, notes, diff)."""
    old, new = precheck.Source(rev), precheck.Source()
    fo, fn = review.facts(old, lid), review.facts(new, lid)
    lo, ln = precheck.Level(old, lid), precheck.Level(new, lid)
    if lo.file is None:
        lo.file = {"pegs": [], "bricks": []}
    if ln.file is None:
        raise SystemExit(f"{lid} has no level file now")
    d = review.diff_pieces(lo.file, ln.file)
    notes = []
    ca, cb = composite_at(old, lid, notes), composite_at(new, lid, notes)
    summary = review.diff_summary(lid, fo, fn, d, rev)
    img = reviewimg.diff_image(ca, cb, d, f"{lid} at {review.rev_short(rev)}  ({fo.get('pieces', 0)} pieces)",
                               f"{lid} now  ({fn.get('pieces', 0)} pieces)", summary + notes)
    out = pathlib.Path(out) if out else DIFFS / f"{lid}-{review.rev_short(rev)}.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out, summary, notes, d


def cmd_diff(args):
    """diff <level-id> --rev <git rev> [--out file.png]"""
    rev, args = _take(args, "--rev")
    out, args = _take(args, "--out")
    if not rev or len(args) != 1:
        print("diff <level-id> --rev <git rev> [--out file.png]")
        return 2
    path, summary, notes, _d = diff_level(args[0], rev, out)
    print("\n".join(summary + notes))
    print("wrote", path)
    return 0


# ----------------------------------------------------------------------------------------------------------- sheet
def caption(f, pre):
    if not f["has_file"]:
        return [(f"{f['code']}  {f['id']}", reviewimg.FG, True), (f["name"], reviewimg.DIM, False), ("no level file yet", reviewimg.DIM, False)]
    ver = f.get("verdict") or "-"
    pv = pre.get(f["id"], (None, ""))
    mg = "-" if f.get("margin") is None else f"{f['margin']:+.1f}"
    band = "-" if not f.get("band") else f"{f['band'][0]:g}-{f['band'][1]:g}"
    return [(f"{f['code']}  {f['id']}", reviewimg.FG, True), (f["name"], reviewimg.FG, False),
            (f"{f['pieces']} pcs, {f['candidates']} cand, low third {round(f['lower_third'] * 100)}%", reviewimg.DIM, False),
            (f"wins {f['ramp']}/48 held-out, {f['won48']}/48 rule", reviewimg.DIM, False),
            (f"band {band}, margin {mg}", reviewimg.VERDICT_COL["FAIL"] if f.get("margin") is not None and f["margin"] < 0 else reviewimg.DIM, False),
            (f"{ver}; precheck {pv[0] or '-'} ({pv[1]})" if pv[0] else f"{ver}", reviewimg.VERDICT_COL.get(pv[0] or ver, reviewimg.FG), False)]


def sheet_cells(ids, with_precheck=True):
    src = precheck.Source()
    pre = review.precheck_verdicts(ids) if with_precheck else {}
    cells = []
    for lid in ids:
        f = review.facts(src, lid)
        cells.append({"composite": src.image(f"composites/{lid}.png"), "caption": caption(f, pre), "facts": f})
    return cells


def sheet_for(ids, key=None, engine_images=None, with_precheck=True, cols=5):
    cells = sheet_cells(ids, with_precheck)
    facts = [c["facts"] for c in cells]
    title = stage_title(key, facts) if key else "levels " + ", ".join(ids)
    return reviewimg.sheet_image(title, cells, cols=cols, engine=engine_images)


def stage_title(key, facts):
    ramps = [f["ramp"] for f in facts if f.get("ramp") is not None]
    lo, hi = stagecheck.MEAN_BANDS[key]
    mean = f"mean {sum(ramps) / len(ramps):.1f}" if len(ramps) == len(facts) and ramps else "mean -"
    return f"{key.upper()}  {len(facts)} levels  {mean} per 48  (band {lo:g} to {hi:g})"


def engine_images_for(ids, out_dir, size="640x400"):
    imgs, notes = [], []
    from PIL import Image
    out_dir.mkdir(parents=True, exist_ok=True)
    src = precheck.Source()
    for lid in ids:
        scene = review.level_meta(lid, src)[2]
        p = out_dir / f"{lid}-engine-{size.split('x')[0]}.png"
        r = review.engine_render(lid, scene, p, size=size)
        if r.startswith("render failed") or "not built" in r:
            notes.append(f"{lid}: {r}")
            imgs.append(None)
        else:
            imgs.append(Image.open(p))
    return imgs, notes


def cmd_sheet(args):
    """sheet <ids...> | --stage <key> [--engine] [--out file.png] [--cols N] [--no-precheck]"""
    stage, args = _take(args, "--stage")
    out, args = _take(args, "--out")
    cols, args = _take(args, "--cols", "5")
    eng, args = _take(args, "--engine", False, has_value=False)
    nopre, args = _take(args, "--no-precheck", False, has_value=False)
    if stage:
        key = stagecheck.stage_key(stage)
        ids, name = review.stage_ids(key), key
    else:
        ids, name, key = args, "-".join(args)[:60], None
    if not ids:
        print("sheet <level-id>... | --stage <key> [--engine] [--out file.png] [--cols N] [--no-precheck]")
        return 2
    eimgs = None
    if eng:
        eimgs, notes = engine_images_for(ids, SHEETS / "engine")
        print("\n".join(notes))
    img = sheet_for(ids, key, eimgs, with_precheck=not nopre, cols=int(cols))
    out = pathlib.Path(out) if out else SHEETS / f"{name}{'-engine' if eng else ''}.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    print("wrote", out, f"({img.width} x {img.height})")
    return 0


# ---------------------------------------------------------------------------------------------------------- status
def cmd_status(args):
    """status --stage <key> | --all [--json] [--no-precheck]"""
    stage, args = _take(args, "--stage")
    js, args = _take(args, "--json", False, has_value=False)
    allv, args = _take(args, "--all", False, has_value=False)
    nopre, args = _take(args, "--no-precheck", False, has_value=False)
    src = precheck.Source()
    if stage:
        ids = review.stage_ids(stagecheck.stage_key(stage), src)
    elif allv:
        ids = src.ids()
    else:
        print("status --stage <key> | --all [--json] [--no-precheck]")
        return 2
    rows = review.status(ids, with_precheck=not nopre)
    if js:
        print(json.dumps(rows, indent=1, default=list))
    else:
        print(review.status_text(rows))
        print("build: fresh = inputs unchanged since the last PASS (stamp; git order when there is no stamp); margin = distance of the "
              "held-out wins to the nearer edge of the stage's mean band (negative: outside)")
    return 0


# ------------------------------------------------------------------------------------------------------------ pack
def pack(key, out=None, since=None, engine=True, force=False, log=print):
    """Write the review pack of stage `key`; returns the output folder. Only levels whose inputs changed are re-rendered."""
    key = stagecheck.stage_key(key)
    src = precheck.Source()
    ids = review.stage_ids(key, src)
    if not ids:
        raise SystemExit(f"no levels found for {key}")
    out = pathlib.Path(out) if out else paths.LEVELS / "review" / key
    out.mkdir(parents=True, exist_ok=True)
    stamp_file = out / ".pack.json"
    try:
        stamps = json.loads(stamp_file.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        stamps = {}
    notes = []
    eng_imgs = []
    from PIL import Image
    for lid in ids:
        for kind, rel in (("composite", f"composites/{lid}.png"), ("report", f"report/{lid}.json")):
            b = src.read(rel)
            dst = out / (f"{lid}-composite.png" if kind == "composite" else f"{lid}-report.json")
            if b is not None and (not dst.exists() or dst.read_bytes() != b):
                dst.write_bytes(b)
        if engine:
            scene = review.level_meta(lid, src)[2]
            res = []
            for size in ("1280x800", "640x400"):
                res.append(review.engine_render(lid, scene, out / f"{lid}-engine-{size.split('x')[0]}.png", size=size, moment="start",
                                                stamps=stamps))
            bad = [r for r in res if r not in ("skipped", "rendered")]
            log(f"[{lid}] engine renders: " + ", ".join(res))
            notes += [f"{lid}: {b}" for b in bad]
            p = out / f"{lid}-engine-1280.png"
            eng_imgs.append(Image.open(p) if p.exists() else None)
    stamp_file.write_text(json.dumps(stamps, indent=1), encoding="utf-8")
    rows = review.status(ids)
    (out / "status.json").write_text(json.dumps(rows, indent=1, default=list), encoding="utf-8")
    sheet = sheet_for(ids, key, eng_imgs if engine else None)
    sheet.save(out / "sheet.png")
    diffs = []
    if since:
        for r in rows:
            lid = r["id"]
            if not r["has_file"]:
                continue
            if review.changed_since(since, lid, r.get("scene")):
                p, summary, n2, _d = diff_level(lid, since, out / f"{lid}-diff.png")
                diffs.append((lid, summary))
                notes += n2
    index = [MARK, f"# Review pack: {key.upper()}", "",
             f"Made by `mfl.py pack --stage {key}` at {time.strftime('%Y-%m-%d %H:%M')} from the working tree"
             + (f"; diffs against {review.rev_short(since)}" if since else "") + ". Reviewers: use these files only; never run a build.", "",
             "## Files", "",
             "| File | What it is |", "|---|---|",
             "| `sheet.png` | contact sheet: composites" + (", engine renders" if engine else "") + ", and each level's figures |",
             "| `base-NN-composite.png` | the pipeline's 1x composite as committed |",
             "| `base-NN-engine-1280.png`, `-640.png` | the plugin's own render (MoonfallRender `--moment start --cache`), what the game ships; it shows the converted runtime files, so check the `convert` column |",
             "| `base-NN-diff.png` | before and after against the `--changed-since` revision (only for changed levels) |",
             "| `base-NN-report.json` | the build report |", "| `status.json` | the table below as data |", "",
             "## Status", "", "```", review.status_text(rows), "```", ""]
    if diffs:
        index += ["## Changed since " + review.rev_short(since), ""]
        for lid, summary in diffs:
            index += [f"### {lid}", "", f"![{lid} diff]({lid}-diff.png)", "", "```", *summary, "```", ""]
    if notes:
        index += ["## Notes", ""] + [f"- {n}" for n in notes] + [""]
    ipath = out / "index.md"
    if ipath.exists() and MARK not in ipath.read_text(encoding="utf-8") and not force:
        ipath = out / "index-generated.md"
        notes.append(f"index.md is hand-written; wrote {ipath.name} instead (--force replaces index.md)")
    ipath.write_text("\n".join(index), encoding="utf-8")
    log(f"pack: {out} ({len(ids)} levels, index {ipath.name})" + "".join(f"\n  note: {n}" for n in notes))
    return out


def cmd_pack(args):
    """pack --stage <key> [--changed-since <rev>] [--out dir] [--no-engine] [--force]"""
    stage, args = _take(args, "--stage")
    since, args = _take(args, "--changed-since")
    out, args = _take(args, "--out")
    noeng, args = _take(args, "--no-engine", False, has_value=False)
    force, args = _take(args, "--force", False, has_value=False)
    if not stage:
        print("pack --stage <key> [--changed-since <rev>] [--out dir] [--no-engine] [--force]")
        return 2
    pack(stage, out=out, since=since, engine=not noeng, force=force)
    return 0


